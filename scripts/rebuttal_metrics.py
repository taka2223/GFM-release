def log(message: str) -> None:
    print(f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {message}", flush=True)


def normalize_pointcloud(points: np.ndarray) -> np.ndarray:
    points = points.astype(np.float32, copy=False)
    points = points - points.mean(axis=0, keepdims=True)
    scale = np.linalg.norm(points, axis=1).max()
    if not np.isfinite(scale) or scale <= 1e-8:
        raise ValueError("Degenerate point cloud")
    return points / scale


class LatentDecoder:
    def __init__(
        self,
        ae: torch.nn.Module,
        device: torch.device,
        density: int,
        num_points: int,
    ) -> None:
        self.ae = ae
        self.device = device
        self.density = density
        self.num_points = num_points
        self.gap = 2.0 / density
        axis = np.linspace(-1, 1, density + 1)
        xv, yv, zv = np.meshgrid(axis, axis, axis)
        self.grid = (
            torch.from_numpy(
                np.stack([xv, yv, zv]).astype(np.float32)
            )
            .reshape(3, -1)
            .T[None]
            .to(device)
        )

    def decode_one(self, latent: torch.Tensor, sample_seed: int) -> torch.Tensor:
        with torch.no_grad():
            logits = self.ae.decode(
                latent[None].to(self.device), self.grid
            )
        volume = (
            logits.float()
            .cpu()
            .reshape(self.density + 1, self.density + 1, self.density + 1)
            .permute(1, 0, 2)
            .numpy()
        )
        vertices, faces = mcubes.marching_cubes(volume, 0)
        if len(vertices) == 0 or len(faces) == 0:
            raise ValueError("Marching cubes returned an empty mesh")
        vertices = vertices * self.gap - 1.0
        mesh = trimesh.Trimesh(vertices=vertices, faces=faces, process=False)
        points, _ = trimesh.sample.sample_surface(
            mesh, self.num_points, seed=sample_seed
        )
        return torch.from_numpy(normalize_pointcloud(points))

    def decode_many(
        self, latents: torch.Tensor, seed_offset: int
    ) -> tuple[torch.Tensor, list[dict[str, Any]]]:
        points: list[torch.Tensor] = []
        failures: list[dict[str, Any]] = []
        for index, latent in enumerate(latents):
            try:
                points.append(self.decode_one(latent, seed_offset + index))
            except Exception as error:
                failures.append(
                    {
                        "index": index,
                        "error_type": type(error).__name__,
                        "error": str(error),
                    }
                )
                points.append(
                    torch.full(
                        (self.num_points, 3), float("nan"), dtype=torch.float32
                    )
                )
            if (index + 1) % 10 == 0 or index + 1 == len(latents):
                log(f"Decoded {index + 1}/{len(latents)} latents")
        return torch.stack(points), failures


def load_autoencoder(
    args: argparse.Namespace, device: torch.device
) -> torch.nn.Module:
    log(f"Loading autoencoder from {args.ae_path}")
    return load_model_from_path(
        model_name=args.ae_name,
        ckpt_path=args.ae_path,
        registry=models_ae.__dict__,
        device=device,
    )


def reference_output(args: argparse.Namespace, category: int) -> Path:
    return (
        args.output_root
        / "decoded"
        / "references"
        / f"category{category:02d}_points{args.num_points}_density{args.density}.pt"
    )


def generated_output(
    args: argparse.Namespace,
    category: int,
    sigma: float,
    lam: float,
    seed: int,
    batch_name: str,
) -> Path:
    return (
        args.output_root
        / "decoded"
        / "generated"
        / f"category{category:02d}"
        / f"sigma{float_slug(sigma)}"
        / f"lambda{float_slug(lam)}"
        / f"seed{seed}"
        / batch_name
    )


def decode_references(
    args: argparse.Namespace, decoder: LatentDecoder
) -> None:
    for category in args.categories:
        destination = reference_output(args, category)
        if destination.exists():
            continue
        latents: list[torch.Tensor] = []
        provenance: list[dict[str, int | str]] = []
        for seed in args.seeds:
            payload = torch.load(
                endpoint_path(args, category, seed),
                map_location="cpu",
                weights_only=False,
            )
            for side in ("start", "end"):
                latents.append(payload[side])
                provenance.extend(
                    {
                        "seed": seed,
                        "side": side,
                        "pair_index": index,
                    }
                    for index in range(payload[side].shape[0])
                )
        all_latents = torch.cat(latents, dim=0)
        points, failures = decoder.decode_many(
            all_latents, seed_offset=category * 10_000_000
        )
        atomic_torch_save(
            {
                "category": category,
                "num_points": args.num_points,
                "density": args.density,
                "provenance": provenance,
                "pointclouds": points,
                "failures": failures,
            },
            destination,
        )
        log(f"Saved fixed reference pool: {destination}")


def decode_generated(args: argparse.Namespace, decoder: LatentDecoder) -> None:
    for category in args.categories:
        for sigma in args.sigmas:
            for lam in args.lambdas:
                for seed in args.seeds:
                    source_dir = condition_dir(
                        args, category, sigma, lam, seed
                    )
                    for payload in iter_batch_payloads(source_dir):
                        pair_start = payload["metadata"]["pair_start"]
                        pair_end = payload["metadata"]["pair_end"]
                        destination = generated_output(
                            args,
                            category,
                            sigma,
                            lam,
                            seed,
                            f"pairs{pair_start:03d}-{pair_end - 1:03d}.pt",
                        )
                        if destination.exists():
                            continue
                        paths = payload["denoised_paths"]
                        flattened = paths.flatten(0, 1)
                        points, failures = decoder.decode_many(
                            flattened,
                            seed_offset=(
                                category * 10_000_000
                                + int(round(sigma * 1000)) * 100_000
                                + int(round((lam + 1) * 100)) * 1_000
                                + seed
                                + pair_start * args.num_waypoints
                            ),
                        )
                        atomic_torch_save(
                            {
                                "category": category,
                                "sigma": sigma,
                                "lambda": lam,
                                "seed": seed,
                                "pair_indices": payload["pair_indices"],
                                "num_waypoints": paths.shape[1],
                                "pointclouds": points.reshape(
                                    paths.shape[0],
                                    paths.shape[1],
                                    args.num_points,
                                    3,
                                ),
                                "failures": failures,
                            },
                            destination,
                        )
                        log(f"Saved decoded paths: {destination}")


def chamfer_pairs(
    generated: torch.Tensor, reference: torch.Tensor
) -> torch.Tensor:
    distances = torch.cdist(generated, reference, p=2).square()
    return (
        distances.min(dim=2).values.mean(dim=1)
        + distances.min(dim=1).values.mean(dim=1)
    )


def minimum_chamfer_distances(
    generated: torch.Tensor,
    reference: torch.Tensor,
    pair_batch_size: int,
) -> tuple[np.ndarray, np.ndarray]:
    device = generated.device
    n_generated = generated.shape[0]
    n_reference = reference.shape[0]
    min_generated = torch.full(
        (n_generated,), float("inf"), device=device
    )
    min_reference = torch.full(
        (n_reference,), float("inf"), device=device
    )
    # pair_batch_size bounds the number of shape pairs evaluated together.
    side = max(1, int(math.sqrt(pair_batch_size)))
    for gen_start in range(0, n_generated, side):
        gen = generated[gen_start : gen_start + side]
        for ref_start in range(0, n_reference, side):
            ref = reference[ref_start : ref_start + side]
            gen_repeated = gen.repeat_interleave(ref.shape[0], dim=0)
            ref_repeated = ref.repeat(gen.shape[0], 1, 1)
            with torch.no_grad():
                block = chamfer_pairs(
                    gen_repeated, ref_repeated
                ).reshape(gen.shape[0], ref.shape[0])
            min_generated[gen_start : gen_start + gen.shape[0]] = torch.minimum(
                min_generated[gen_start : gen_start + gen.shape[0]],
                block.min(dim=1).values,
            )
            min_reference[ref_start : ref_start + ref.shape[0]] = torch.minimum(
                min_reference[ref_start : ref_start + ref.shape[0]],
                block.min(dim=0).values,
            )
        log(
            f"Chamfer rows: {min(gen_start + gen.shape[0], n_generated)}"
            f"/{n_generated}"
        )
    return (
        min_generated.sqrt().cpu().numpy(),
        min_reference.sqrt().cpu().numpy(),
    )


def load_generated_points(
    args: argparse.Namespace,
    category: int,
    sigma: float,
    lam: float,
    seed: int,
) -> tuple[torch.Tensor, list[dict[str, Any]]]:
    directory = generated_output(
        args, category, sigma, lam, seed, "placeholder"
    ).parent
    tensors: list[torch.Tensor] = []
    failures: list[dict[str, Any]] = []
    for path in sorted(directory.glob("pairs*.pt")):
        payload = torch.load(path, map_location="cpu", weights_only=False)
        tensors.append(payload["pointclouds"].flatten(0, 1))
        failures.extend(payload["failures"])
    if not tensors:
        raise FileNotFoundError(f"No decoded paths in {directory}")
    points = torch.cat(tensors, dim=0)
    finite = torch.isfinite(points).flatten(start_dim=1).all(dim=1)
    failures.extend(
        {"index": int(index), "error": "nonfinite_pointcloud"}
        for index in (~finite).nonzero(as_tuple=False).flatten()
    )
    return points[finite], failures


def compute_metrics(
    min_generated: np.ndarray,
    min_reference: np.ndarray,
    threshold: float,
) -> dict[str, float]:
    precision = float((min_generated < threshold).mean())
    recall = float((min_reference < threshold).mean())
    f_score = 2 * precision * recall / (precision + recall + 1e-12)
    return {
        "MMD": float(min_reference.mean()),
        "CD99": float(np.percentile(min_generated, 99)),
        f"F@{threshold:g}": float(f_score),
        f"precision@{threshold:g}": precision,
        f"recall@{threshold:g}": recall,
    }


def metric_output(
    args: argparse.Namespace,
    category: int,
    sigma: float,
    lam: float,
    seed: int,
) -> Path:
    return (
        args.output_root
        / "metrics"
        / "per_seed"
        / (
            f"category{category:02d}_sigma{float_slug(sigma)}"
            f"_lambda{float_slug(lam)}_seed{seed}.json"
        )
    )


def evaluate(args: argparse.Namespace, device: torch.device) -> None:
    for category in args.categories:
        reference_payload = torch.load(
            reference_output(args, category),
            map_location="cpu",
            weights_only=False,
        )
        reference = reference_payload["pointclouds"]
        reference_finite = torch.isfinite(reference).flatten(start_dim=1).all(dim=1)
        reference = reference[reference_finite].to(device)
        for sigma in args.sigmas:
            for lam in args.lambdas:
                for seed in args.seeds:
                    destination = metric_output(
                        args, category, sigma, lam, seed
                    )
                    if destination.exists():
                        continue
                    generated, failures = load_generated_points(
                        args, category, sigma, lam, seed
                    )
                    min_generated, min_reference = minimum_chamfer_distances(
                        generated.to(device),
                        reference,
                        args.pair_batch_size,
                    )
                    metrics = compute_metrics(
                        min_generated, min_reference, args.threshold
                    )
                    atomic_json_dump(
                        {
                            "category": category,
                            "sigma": sigma,
                            "lambda": lam,
                            "seed": seed,
                            "n_generated": int(generated.shape[0]),
                            "n_reference": int(reference.shape[0]),
                            "decode_failure_count": len(failures),
                            **metrics,
                        },
                        destination,
                    )
                    np.savez_compressed(
                        destination.with_suffix(".npz"),
                        min_generated_to_reference=min_generated,
                        min_reference_to_generated=min_reference,
                    )
                    log(f"Saved metrics: {destination}")


def aggregate(args: argparse.Namespace) -> None:
    rows: list[dict[str, Any]] = []
    metric_names = ["MMD", "CD99", f"F@{args.threshold:g}"]
    for category in args.categories:
        for sigma in args.sigmas:
            for lam in args.lambdas:
                records = [
                    json.loads(
                        metric_output(
                            args, category, sigma, lam, seed
                        ).read_text(encoding="utf-8")
                    )
                    for seed in args.seeds
                    if metric_output(
                        args, category, sigma, lam, seed
                    ).exists()
                ]
                if not records:
                    continue
                row: dict[str, Any] = {
                    "category": category,
                    "sigma": sigma,
                    "lambda": lam,
                    "completed_seeds": len(records),
                    "expected_seeds": len(args.seeds),
                }
                for metric in metric_names:
                    values = np.asarray(
                        [record[metric] for record in records], dtype=np.float64
                    )
                    row[f"{metric}_mean"] = float(values.mean())
                    row[f"{metric}_std"] = (
                        float(values.std(ddof=1)) if len(values) > 1 else 0.0
                    )
                rows.append(row)

    output_dir = args.output_root / "summaries" / "e1_metrics"
    atomic_json_dump(rows, output_dir / "summary.json")
    output_dir.mkdir(parents=True, exist_ok=True)
    if rows:
        with (output_dir / "summary.csv").open(
            "w", newline="", encoding="utf-8"
        ) as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
        category_names = {5: "Bed", 47: "Sofa"}
        markdown = [
            "# E1 λ Sensitivity",
            "",
            "Values are mean ± sample standard deviation across paired seeds.",
            "",
        ]
        for category in args.categories:
            for sigma in args.sigmas:
                markdown.extend(
                    [
                        f"## {category_names.get(category, category)}, σ={sigma:g}",
                        "",
                        "| λ | Seeds | MMD | CD99 | F@0.1 |",
                        "|---:|---:|---:|---:|---:|",
                    ]
                )
                for row in rows:
                    if row["category"] != category or row["sigma"] != sigma:
                        continue
                    markdown.append(
                        f"| {row['lambda']:g} "
                        f"| {row['completed_seeds']}/{row['expected_seeds']} "
                        f"| {row['MMD_mean']:.4f} ± {row['MMD_std']:.4f} "
                        f"| {row['CD99_mean']:.4f} ± {row['CD99_std']:.4f} "
                        f"| {row['F@0.1_mean']:.4f} ± "
                        f"{row['F@0.1_std']:.4f} |"
                    )
                markdown.append("")
        (output_dir / "summary.md").write_text(
            "\n".join(markdown), encoding="utf-8"
        )
    log(f"Wrote E1 metric summaries to {output_dir}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--phase",
        choices=["all", "decode", "evaluate", "aggregate"],
        default="all",
    )
    parser.add_argument("--categories", type=int, nargs="+", default=DEFAULT_CATEGORIES)
    parser.add_argument("--sigmas", type=float, nargs="+", default=DEFAULT_SIGMAS)
    parser.add_argument("--lambdas", type=float, nargs="+", default=DEFAULT_LAMBDAS)
    parser.add_argument("--seeds", type=int, nargs="+", default=DEFAULT_SEEDS)
    parser.add_argument("--num-pairs", type=int, default=50)
    parser.add_argument("--num-waypoints", type=int, default=10)
    parser.add_argument("--num-points", type=int, default=2048)
    parser.add_argument("--density", type=int, default=128)
    parser.add_argument("--threshold", type=float, default=0.1)
    parser.add_argument("--pair-batch-size", type=int, default=16)
    parser.add_argument("--ae-name", default="kl_d512_m512_l8")
    parser.add_argument(
        "--ae-path",
        type=Path,
        default=ROOT / "ae" / "kl_d512_m512_l8" / "checkpoint-199.pth",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=ROOT / "artifacts" / "rebuttal",
    )
    return parser


def main() -> None:
    args = build_parser().parse_args()
    args.output_root = args.output_root.resolve()
    args.ae_path = args.ae_path.resolve()
    if not torch.cuda.is_available() and args.phase != "aggregate":
        raise RuntimeError("CUDA is required for decoding and Chamfer evaluation")
    device = torch.device("cuda:0")

    if args.phase in {"all", "decode"}:
        ae = load_autoencoder(args, device)
        decoder = LatentDecoder(ae, device, args.density, args.num_points)
        decode_references(args, decoder)
        decode_generated(args, decoder)
        del decoder, ae
        torch.cuda.empty_cache()
    if args.phase in {"all", "evaluate"}:
        evaluate(args, device)
    if args.phase in {"all", "aggregate"}:
        aggregate(args)


if __name__ == "__main__":
    main()
